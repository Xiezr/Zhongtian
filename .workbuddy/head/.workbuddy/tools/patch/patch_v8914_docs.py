def _read(path):
    return io.open(R + '\\' + path, encoding='utf-8', newline='').read()


def _write(path, s):
    io.open(R + '\\' + path, 'w', encoding='utf-8', newline='').write(s)


def fix(path, old, new, tag):
    src = _read(path)
    eol = '\r\n' if '\r\n' in src else '\n'
    o = old.replace('\n', eol)
    nw = new.replace('\n', eol)
    n = src.count(o)
    if n != 1:
        print('FAIL [%s] 命中 %d 次' % (tag, n))
        sys.exit(1)
    _write(path, src.replace(o, nw, 1))
    back = _read(path)
    assert nw in back, tag
    print('OK  ' + tag)


def append(path, text, marker, tag):
    src = _read(path)
    if marker in src:
        print('SKIP（已含）：' + tag)
        return
    eol = '\r\n' if '\r\n' in src else '\n'
    if not src.endswith('\n'):
        src += eol
    _write(path, src + text.replace('\n', eol))
    back = _read(path)
    assert marker in back, tag
    print('OK  ' + tag)


