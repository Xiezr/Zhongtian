report = {}
for f in DOCS:
    p = BASE + f
    s = io.open(p, encoding='utf-8', newline='').read()
    orig = s
    detail = []
    for old, new in MED:
        c = s.count(old)
        if c:
            s = s.replace(old, new)
            detail.append((old, new, c))
    # 数字+金
    pat = re.compile(r'([0-9])(\s*)金(?![' + GOLD_TAIL + '])')
    ng = len(pat.findall(s))
    s = pat.sub(r'\1\2旧币', s)
