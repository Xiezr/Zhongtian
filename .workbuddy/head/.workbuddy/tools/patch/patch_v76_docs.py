def patch(path, old, new, tag):
    t = io.open(path, encoding='utf-8', newline='').read()
    if new in t or new.replace('\n', '\r\n') in t:
        print('  · %s：已改过（跳过）' % tag)
        return
    c = t.count(old)
    if c != 1:
        print('  ✗ %s：锚点命中 %d 次，拒绝写盘' % (tag, c))
        sys.exit(1)
    io.open(path, 'w', encoding='utf-8', newline='').write(t.replace(old, new, 1))
    print('  ✓ %s' % tag)


def append_doc(path, probe, text, tag):
    t = io.open(path, encoding='utf-8', newline='').read()
    if probe in t:
        print('  · %s：已追加（跳过）' % tag)
        return
    crlf = t.count('\r\n') > (t.count('\n') - t.count('\r\n'))
    body = text.replace('\n', '\r\n') if crlf else text
    if t.endswith('\r\n\r\n') or t.endswith('\n\n'):
        out = t + body
    elif t.endswith('\r\n') or t.endswith('\n'):
        out = t + ('\r\n' if crlf else '\n') + body
    else:
        out = t + ('\r\n\r\n' if crlf else '\n\n') + body
    io.open(path, 'w', encoding='utf-8', newline='').write(out)
    print('  ✓ %s' % tag)


