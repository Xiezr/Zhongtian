def rd(p):
    return io.open(p, encoding='utf-8', newline='').read()


def wr(p, s):
    io.open(p, 'w', encoding='utf-8', newline='').write(s)


def sub_checked(s, old, new, tag, expect=None):
    c = s.count(old)
    if c == 0:
        print('  [miss] %s  ← %s' % (tag, old[:40]))
        return s
    if expect is not None and c != expect:
        raise SystemExit('❌ %s: count=%d expect=%d  [%s]' % (tag, c, expect, old[:40]))
    print('  [ok] %s x%d  %s → %s' % (tag, c, old[:26], new[:26]))
    return s.replace(old, new)


