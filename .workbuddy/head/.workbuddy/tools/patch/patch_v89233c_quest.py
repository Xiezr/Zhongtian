    i = s.find("{ id: '%s'" % qid)
    assert i >= 0, 'id miss ' + qid
    j = s.find("{ id: '", i + 10)
    if j < 0:
        j = i + 700
    seg = s[i:j]
    seg2 = re.sub(r"title: '[^']*'", "title: '%s'" % nt, seg, count=1)
    assert ("title: '%s'" % nt) in seg2, 'title bad ' + qid
    seg3 = re.sub(r"desc: '[^']*'", lambda m: "desc: '%s'" % nd, seg2, count=1)
    assert ("desc: '%s'" % nd) in seg3, 'desc bad ' + qid
    s = s[:i] + seg3 + s[j:]
    LOG.append('[ok] ' + qid)

