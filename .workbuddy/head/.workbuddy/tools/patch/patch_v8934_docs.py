def read(p):
    return io.open(p, encoding='utf-8', newline='').read()


def is_crlf(p):
    d = io.open(p, 'rb').read()
    crlf = d.count(b'\r\n'); lf = d.count(b'\n') - crlf
    return crlf > 0 and crlf >= lf


def write(p, src):
    tmp = p + '.tmp8934'
    io.open(tmp, 'w', encoding='utf-8', newline='').write(src)
    os.replace(tmp, p)


def edit(p, old, new, tag):
    src = read(p)
    if is_crlf(p):
        old = old.replace('\r\n', '\n').replace('\n', '\r\n')
        new = new.replace('\r\n', '\n').replace('\n', '\r\n')
    n = src.count(old)
    if n != 1:
        print('FAIL [%s] 命中 %d 次' % (tag, n)); sys.exit(1)
    write(p, src.replace(old, new, 1))
    back = read(p)
    probe = new.split('\r\n')[0].split('\n')[0].strip()
    assert probe and probe in back, tag
    print('OK  ' + tag)


def append(p, text, tag):
    src = read(p)
    if is_crlf(p): text = text.replace('\r\n', '\n').replace('\n', '\r\n')
    if not src.endswith('\n'): src += '\r\n' if is_crlf(p) else '\n'
    write(p, src + text)
    back = read(p)
    head = text.strip().split('\r\n')[0].split('\n')[0].strip()
    assert head and head in back, tag
    print('OK  ' + tag)


