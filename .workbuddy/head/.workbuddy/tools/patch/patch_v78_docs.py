def append(path, text, eol, tag):
    t = io.open(path, encoding='utf-8', newline='').read()
    marker = text.split('\n')[0]
    if marker in t:
        print('  · %s：已追加过（跳过）' % tag)
        return
    add = eol + text.replace('\n', eol)
    io.open(path, 'w', encoding='utf-8', newline='').write(t + add)
    print('  ✓ %s' % tag)


