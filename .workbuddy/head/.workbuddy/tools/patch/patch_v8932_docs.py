def edit(p, pairs, tag):
    src = read(p)
    for old, new, name in pairs:
        n = src.count(old)
        if n != 1:
            print('FAIL [%s -> %s] 命中 %d 次' % (tag, name, n))
            sys.exit(1)
        src = src.replace(old, new, 1)
    write(p, src)
    back = read(p)
    for _, new, name in pairs:
        assert new in back, '%s / %s' % (tag, name)
    print('OK  ' + tag)


def append(p, text, crlf):
    src = read(p)
    if not src.endswith('\n'):
        src += '\r\n' if crlf else '\n'
    block = text.replace('\n', '\r\n') if crlf else text
    write(p, src + block)
    back = read(p)
    assert text.strip().split('\n')[0] in back
    print('OK  append ' + os.path.basename(p))


