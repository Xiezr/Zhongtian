import io
import os
import sys

R = r'E:\Deepseekdb'


def read(p):
    return io.open(p, encoding='utf-8', newline='').read()


def write(p, s):
    io.open(p, 'w', encoding='utf-8', newline='').write(s)


def edit(path, pairs, tag):
    p = os.path.join(R, path)
    raw = io.open(p, 'rb').read()
    crlf = b'\r\n' in raw
    src = read(p)

    def M(s):
        return s.replace('\n', '\r\n') if crlf else s

    for i, (old, new) in enumerate(pairs):
        o, n = M(old), M(new)
        c = src.count(o)
        if c != 1:
            print('FAIL [%s #%d] 命中 %d 次' % (tag, i + 1, c))
            sys.exit(1)
        src = src.replace(o, n, 1)
    write(p, src)
    back = read(p)
    for i, (old, new) in enumerate(pairs):
        if M(new) not in back:
            print('FAIL [%s #%d] 落盘回查失败' % (tag, i + 1))
            sys.exit(1)
    print('OK  ' + tag)


def append(path, text, marker):
    p = os.path.join(R, path)
    raw = io.open(p, 'rb').read()
    crlf = b'\r\n' in raw
    src = read(p)
    if marker in src:
        print('SKIP（已含 %s）：%s' % (marker, path))
        return
    block = text.replace('\n', '\r\n') if crlf else text
    if not src.endswith('\n'):
        src += '\r\n' if crlf else '\n'
    write(p, src + block)
    back = read(p)
    assert marker in back, '落盘回查失败：' + path
    print('OK  ' + path)


