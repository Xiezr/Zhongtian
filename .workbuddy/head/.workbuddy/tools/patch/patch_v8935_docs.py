import io, sys, os, re

def read(p):
    return io.open(p, encoding='utf-8', newline='').read()

def write(p, s):
    tmp = p + '.tmp8935d'
    io.open(tmp, 'w', encoding='utf-8', newline='').write(s)
    os.replace(tmp, p)

def eol_of(src, pos):
    """取 pos 处紧跟的行尾风格"""
    if src[pos:pos+2] == '\r\n': return '\r\n'
    if src[pos:pos+1] == '\n': return '\n'
    return '\n'

def replace_line(p, prefix, new_lines, tag):
    """把以 prefix 开头的整行（不含行尾）替换为 new_lines（list[str]，自动 EOL）"""
    src = read(p)
    i = src.find(prefix)
    if i < 0:
        print('FAIL [%s] 找不到行首：%s' % (tag, prefix[:40])); sys.exit(1)
    j = i
    while j < len(src) and src[j] not in '\r\n':
        j += 1
    eol = eol_of(src, j)
    new = eol.join(new_lines)
    src2 = src[:i] + new + src[j:]
    write(p, src2)
    back = read(p)
    assert new_lines[0] in back, tag
    print('OK  ' + tag)

def insert_before_line(p, prefix, new_lines, tag):
    src = read(p)
    i = src.find(prefix)
    if i < 0:
        print('FAIL [%s] 找不到插入锚点：%s' % (tag, prefix[:40])); sys.exit(1)
    eol = eol_of(src, i + len(prefix))
    # 锚点行自身的行尾
    j = i + len(prefix)
    while j < len(src) and src[j] not in '\r\n':
        j += 1
    eol = eol_of(src, j)
    new = eol.join(new_lines) + eol
    write(p, src[:i] + new + src[i:])
    back = read(p)
    assert new_lines[0] in back, tag
    print('OK  ' + tag)

def append(p, text, tag):
    src = read(p)
    # 探测主 EOL
    crlf = src.count('\r\n'); lf = src.count('\n') - crlf
    eol = '\r\n' if crlf > lf else '\n'
    block = text.replace('\n', eol)
    if not src.endswith(eol):
        src = src.rstrip('\r\n') + eol
    write(p, src + block)
    back = read(p)
    assert text.strip().split('\n')[0].strip() in back, tag
    print('OK  ' + tag)

