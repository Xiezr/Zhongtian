def read(p):
    return io.open(p, encoding='utf-8', newline='').read()


def eol_of(p):
    raw = io.open(p, 'rb').read()
    crlf = raw.count(b'\r\n'); lf = raw.count(b'\n') - crlf
    return '\r\n' if crlf > lf else '\n'


def write(p, s):
    tmp = p + '.tmp8937d'
    io.open(tmp, 'w', encoding='utf-8', newline='').write(s)
    os.replace(tmp, p)


def edit(p, old, new, tag):
    src = read(p)
    k = src.count(old)
    if k == 1:
        write(p, src.replace(old, new, 1))
        assert new in read(p), '落盘回查失败：' + tag
        print('OK  ' + tag)
        return
    if k == 0 and new in src:
        print('SKIP（已应用） ' + tag)
        return
    print('FAIL [%s] 命中 %d 次' % (tag, k)); sys.exit(1)


def append(p, text, tag):
    src = read(p)
    eol = eol_of(p)
    if text.replace('\n', eol) in src:
        print('SKIP（已应用） ' + tag)
        return
    body = src.rstrip('\r\n \t') + eol + eol + text.replace('\n', eol) + eol
    write(p, body)
    assert text.split('\n')[0] in read(p), '落盘回查失败：' + tag
    print('OK  ' + tag)


