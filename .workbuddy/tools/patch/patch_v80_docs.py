def patch(path, old, new, tag):
    t = io.open(path, encoding='utf-8', newline='').read()
    if new in t:
        print('  · %s：已改过（跳过）' % tag)
        return
    if old in t:
        old2, new2 = old, new
    elif old.replace('\n', '\r\n') in t:
        old2, new2 = old.replace('\n', '\r\n'), new.replace('\n', '\r\n')
    else:
        print('  ✗ %s：锚点不匹配，拒绝写盘' % tag)
        sys.exit(1)
    if t.count(old2) != 1:
        print('  ✗ %s：锚点命中 %d 次（须唯一），拒绝写盘' % (tag, t.count(old2)))
        sys.exit(1)
    io.open(path, 'w', encoding='utf-8', newline='').write(t.replace(old2, new2, 1))
    print('  ✓ %s' % tag)


def append(path, text, eol, tag):
    t = io.open(path, encoding='utf-8', newline='').read()
    marker = next((ln for ln in text.split('\n') if ln.strip()), text[:40])
    if marker in t:
        print('  · %s：已追加过（跳过）' % tag)
        return
    io.open(path, 'w', encoding='utf-8', newline='').write(t + eol + text.replace('\n', eol))
    print('  ✓ %s' % tag)


