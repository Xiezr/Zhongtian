def append_sec(path, marker, text):
    t = io.open(path, encoding='utf-8', newline='').read()
    if marker in t:
        print('  · %s：已改过（跳过）' % os.path.basename(path))
        return
    eol = '\r\n' if t.count('\r\n') > (t.count('\n') - t.count('\r\n')) else '\n'
    io.open(path, 'w', encoding='utf-8', newline='').write(t + text.replace('\n', eol))
    print('  ✓ %s 追加' % os.path.basename(path))


