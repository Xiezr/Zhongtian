def read(p):
    return io.open(p, encoding='utf-8', newline='').read()


def write(p, src):
    tmp = p + '.tmp8938d'
    io.open(tmp, 'w', encoding='utf-8', newline='').write(src)
    os.replace(tmp, p)


def repl_span(p, old, new, tag):
    src = read(p)
    if new in src and old not in src:
        print('SKIP  ' + tag + '（已应用）')
        return
    n = src.count(old)
    if n != 1:
        print('FAIL [%s] 命中 %d' % (tag, n))
        sys.exit(1)
    write(p, src.replace(old, new, 1))
    assert new in read(p), '落盘回查失败：' + tag
    print('OK  ' + tag)


def repl_line(p, key, new_line, tag):
    """按行首特征定位整行并替换（不含行尾）"""
    src = read(p)
    if new_line in src and key not in src:
        print('SKIP  ' + tag + '（已应用）')
        return
    i = src.find(key)
    if i < 0 or (i > 0 and src[i - 1] != '\n'):
        print('FAIL [%s] 找不到行首' % tag)
        sys.exit(1)
    j = src.find('\n', i)
    if j < 0:
        print('FAIL [%s] 找不到行尾' % tag)
        sys.exit(1)
    write(p, src[:i] + new_line + src[j:])
    assert new_line in read(p), '落盘回查失败：' + tag
    print('OK  ' + tag)


def ins_after_line(p, key, block, tag):
    """在行首特征行之后插入 block（block 自带换行结构）"""
    src = read(p)
    i = src.find(key)
    if i < 0 or (i > 0 and src[i - 1] != '\n'):
        print('FAIL [%s] 找不到行首' % tag)
        sys.exit(1)
    j = src.find('\n', i) + 1
    if block in src:
        print('SKIP  ' + tag + '（已应用）')
        return
    write(p, src[:j] + block + src[j:])
    assert block.strip().split('\n')[0] in read(p), '落盘回查失败：' + tag
    print('OK  ' + tag)


def append(p, text, tag, crlf=False):
    src = read(p)
    if text.strip() in src:
        print('SKIP  ' + tag + '（已应用）')
        return
    if crlf:
        text = text.replace('\n', '\r\n')
    if not src.endswith('\n'):
        src += '\r\n' if crlf else '\n'
    write(p, src + text)
    head = text.strip().split('\n')[0].strip()
    assert head in read(p), '落盘回查失败：' + tag
    print('OK  ' + tag)


