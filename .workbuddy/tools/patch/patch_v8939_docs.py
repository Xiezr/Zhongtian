def repl_line(p, key, new_cont, tag):
    """按行首定位整行，替换行内容（保留原行尾）"""
    src = read(p)
    if new_cont.split('\n')[0] in src and key not in src:
        print('SKIP  ' + tag + '（已应用）')
        return
    i = src.find(key)
    if i < 0 or (i > 0 and src[i - 1] != '\n'):
        print('FAIL [%s] 找不到行首' % tag)
        sys.exit(1)
    j = src.find('\n', i)
    eol = '\r\n' if (j > 0 and src[j - 1] == '\r') else '\n'
    write(p, src[:i] + new_cont + eol + src[j + 1:])
    assert new_cont.split('\n')[0] in read(p), '落盘回查失败：' + tag
    print('OK  ' + tag)


def ins_after_line(p, key, block, tag):
    """在行首定位的行之后插入 block（自带行尾）"""
    src = read(p)
    if block.strip().split('\n')[0] in src:
        print('SKIP  ' + tag + '（已应用）')
        return
    i = src.find(key)
    if i < 0 or (i > 0 and src[i - 1] != '\n'):
        print('FAIL [%s] 找不到行首' % tag)
        sys.exit(1)
    j = src.find('\n', i) + 1
    write(p, src[:j] + block + src[j:])
    assert block.strip().split('\n')[0] in read(p), '落盘回查失败：' + tag
    print('OK  ' + tag)


def append(p, text, tag, crlf=False):
    src = read(p)
    if text.strip().split('\n')[0].strip() in src:
        print('SKIP  ' + tag + '（已应用）')
        return
    t = text.replace('\n', '\r\n') if crlf else text
    if not src.endswith('\n'):
        src += '\r\n' if crlf else '\n'
    write(p, src + t)
    print('OK  ' + tag)


