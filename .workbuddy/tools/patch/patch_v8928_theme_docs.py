def norm(text, src):
    """把文本里的 \n 归一为文件自身的行尾（CRLF / LF 自适应）"""
    eol = '\r\n' if ('\r\n' in src[:3000]) else '\n'
    if eol == '\r\n':
        text = text.replace('\r\n', '\n').replace('\n', '\r\n')
    return text


def edit(p, pairs, tag):
    src = read(p)
    for old, new, name in pairs:
        n = src.count(old)
        if n != 1:
            print('FAIL [%s -> %s] 命中 %d 次' % (tag, name, n))
            sys.exit(1)
        src = src.replace(old, norm(new, src), 1)
    write(p, src)
    back = read(p)
    for _, new, name in pairs:
        assert norm(new, back) in back, '%s / %s' % (tag, name)
    print('OK  ' + tag)


def append(p, text):
    src = read(p)
    if not src.endswith('\n'):
        src += '\r\n' if ('\r\n' in src[:3000]) else '\n'
    write(p, src + norm(text, src))
    back = read(p)
    first = norm(text, back).strip().split('\r\n')[0].split('\n')[0]
    assert first in back, p
    print('OK  append ' + os.path.basename(p))


