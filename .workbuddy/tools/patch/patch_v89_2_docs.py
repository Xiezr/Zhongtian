import io

def append(path, sec, tag):
    d = io.open(path, encoding='utf-8', newline='').read()
    if tag in d:
        print('SKIP ' + tag)
        return
    nl = '\r\n' if '\r\n' in d[:4000] else '\n'
    if not d.endswith('\n'):
        d += nl
    body = sec.replace('\n', nl)
    d = d + nl + body + nl
    io.open(path, 'w', encoding='utf-8', newline='').write(d)
    print('OK ' + tag)

