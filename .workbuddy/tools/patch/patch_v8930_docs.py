def read(p):
    return io.open(p, encoding='utf-8', newline='').read()


def write(p, src):
    tmp = p + '.tmp8930d'
    io.open(tmp, 'w', encoding='utf-8', newline='').write(src)
    os.replace(tmp, p)


def nl_of(src):
    return '\r\n' if '\r\n' in src[:4000] else '\n'


def edit(p, pairs, tag):
    src = read(p)
    nl = nl_of(src)
    for old, new, name in pairs:
        old2 = old.replace('\n', nl)
        new2 = new.replace('\n', nl)
        n = src.count(old2)
        if n != 1:
            print('FAIL [%s -> %s] 命中 %d 次' % (tag, name, n))
            sys.exit(1)
        src = src.replace(old2, new2, 1)
    write(p, src)
    back = read(p)
    for old, new, name in pairs:
        assert new.replace('\n', nl) in back, '%s / %s 回查失败' % (tag, name)
    print('OK  ' + tag)


def append(p, text, tag):
    src = read(p)
    nl = nl_of(src)
    if not src.endswith('\n'):
        src += nl
    write(p, src + text.replace('\n', nl))
    back = read(p)
    head = text.strip().split('\n')[0]
    assert head in back, tag + ' 回查失败'
    print('OK  ' + tag)


