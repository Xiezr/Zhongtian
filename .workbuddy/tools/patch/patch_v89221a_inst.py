import io, sys

R = 'E:/Deepseekdb/'
def rd(p): return io.open(p, encoding='utf-8', newline='').read()
def wr(p, s): io.open(p, 'w', encoding='utf-8', newline='').write(s)

bad = []
def rep(path, old, new, expect=None, tag=''):
    global bad
    s = rd(R + path)
    c = s.count(old)
    if expect is not None and c != expect:
        bad.append('%s [%s] count=%d expect=%s | %s' % (path, tag, c, expect, old[:44]))
        return
    if c == 0:
        bad.append('%s [%s] count=0 | %s' % (path, tag, old[:44]))
        return
    wr(R + path, s.replace(old, new))
    print('  [ok] %s x%d %s' % (path.split('/')[-1], c, (tag or old[:22])))

