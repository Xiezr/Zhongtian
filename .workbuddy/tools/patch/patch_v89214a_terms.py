# 前置修正：把会与"上造"撞车的注释改写（否则 '上造'→'管事' 会打出病句）
PRE = [
    ('js/domain.js', '在 B 城的界面上造 A 城的箭塔', '在 B 城的界面上建设 A 城的箭塔'),
]

def apply(path):
    p = R + path
    s = io.open(p, encoding='utf-8', newline='').read()
    s0 = s
    hits = []
    for f2, a, b in PRE:
        if f2 == path and a in s:
            s = s.replace(a, b); hits.append('PRE %s x1' % a)
    for old, new in MAP:
        c = s.count(old)
        if c:
            s = s.replace(old, new)
            hits.append('%s->%s x%d' % (old, new, c))
    if s != s0:
        io.open(p, 'w', encoding='utf-8', newline='').write(s)
    return hits

total = {}
for f in FILES:
    try:
        h = apply(f)
    except Exception as e:
        print('ERR %s: %s' % (f, e)); sys.exit(1)
    if h:
        print('== %s ==' % f)
        for x in h: print('   ' + x)
        for x in h:
            k = x.split('->')[0]
            total[k] = total.get(k, 0) + int(x.split('x')[-1])
print('\n合计 %d 个词、%d 次替换' % (len(total), sum(total.values())))
