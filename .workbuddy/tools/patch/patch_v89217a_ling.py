def apply_terms(files):
    tot = {}
    for f in files:
        p = R + f
        s = io.open(p, encoding='utf-8', newline='').read()
        for old, new in TERMS:
            c = s.count(old)
            if c:
                s = s.replace(old, new)
                tot[old] = tot.get(old, 0) + c
        io.open(p, 'w', encoding='utf-8', newline='').write(s)
    return tot

if __name__ == '__main__':
    tot = apply_terms(FILES)
    print('== 机械词表 ==')
    for k, v in tot.items():
        print('   %s x%d' % (k, v))
    bad = []
    for f, old, new in (T + VISITS):
        p = R + f
        s = io.open(p, encoding='utf-8', newline='').read()
        c = s.count(old)
        if c == 0 and new in s:
            continue
        if c != 1:
            bad.append('%s | x%d | %s' % (f, c, old[:60].replace('\n', '⏎')))
            continue
        io.open(p, 'w', encoding='utf-8', newline='').write(s.replace(old, new))
    if bad:
        print('❌ 定向重写失配 %d：' % len(bad))
        for b in bad: print('   ' + b)
        sys.exit(1)
    print('✅ PART C 完成：机械词 %d 类 · 定向重写 %d 条' % (len(tot), len(T) + len(VISITS)))
