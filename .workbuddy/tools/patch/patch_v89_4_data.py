"""v89.4 数据 —— js/data.js：DATA.JH_SPREAD（野地生态参数）"""
import io

P = r'E:\Deepseekdb\js\data.js'
d = io.open(P, encoding='utf-8', newline='').read()

ANCHOR = ("  /* ============================================================\n"
          "   * v89 · 全屏江湖场景剧本（老板：「专属全屏交互 + 特定退出」）")

BLOCK = r"""  /* ============================================================
   * v89.4（老板：「不同野地有不同活动，不是所有野地都有活动，概率出现，
   *   活动难度跟奖励与野地等级有关」）：野地生态
   * ------------------------------------------------------------
   * · 逐地分布：某格出现哪些活动 = f(格子坐标) 的确定性伪随机 ——
   *   同格恒同貌（跨会话一致；不加日盐，避免每日重抽破坏可复现与测试）
   * · 不是所有野地都有事：先掷「荒僻率」，荒僻格不生江湖之事
   * · 有事格 1~3 事：不同野地得到不同组合（候选按种子洗牌裁剪）
   * · 等级联动（lv = 该格野地等级 0~10）：
   *     难度 ×(1 + lv×lvNeed)（战斗 / 试炼）· 负伤 ×(1 + lv×lvDmg)
   *     收益 ×(1 + lv×lvRew)（精华 / 金 / 粮 / 材料 —— 全走 mi() 出口）
   * ============================================================ */
  DATA.JH_SPREAD = {
    noneP: 0.30,    /* 荒僻率：30% 野地无江湖之事 */
    p2: 0.62,       /* 有事格：< p2 → 1 事 */
    p3: 0.87,       /*         < p3 → 2 事；≥ p3 → 3 事 */
    lvNeed: 0.35,   /* 难度系数（对齐旧常量 0.35） */
    lvDmg: 0.20,    /* 负伤系数 */
    lvRew: 0.30,    /* 收益系数 */
  };

"""

if 'DATA.JH_SPREAD' in d:
    print('SKIP data.js 已含 JH_SPREAD')
else:
    c = d.count(ANCHOR)
    if c != 1:
        raise SystemExit('!! data.js 锚点异常（出现 %d 次）' % c)
    d = d.replace(ANCHOR, BLOCK + ANCHOR, 1)
    io.open(P, 'w', encoding='utf-8', newline='').write(d)
    print('OK data.js 已加 DATA.JH_SPREAD')
