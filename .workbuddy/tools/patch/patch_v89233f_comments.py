import io

R = 'E:/Deepseekdb/'
LOG = []


def rep(path, tag, old, new, cnt=1):
    p = R + path
    s = io.open(p, encoding='utf-8', newline='').read()
    c = s.count(old)
    assert c == cnt, '%s · %s count=%d want=%d' % (path, tag, c, cnt)
    s = s.replace(old, new)
    io.open(p, 'w', encoding='utf-8', newline='').write(s)
    LOG.append('[ok] %s · %s' % (path, tag))


