# -*- coding: utf-8 -*-
"""v89.137 补丁 A：data.js —— 建筑专精三档表（DATA.MASTERY_TIERS）与文案更名"""
import io, sys, os

ROOT = 'E:/Deepseekdb'
p = os.path.join(ROOT, 'js', 'data.js')
s = io.open(p, 'r', encoding='utf-8', newline='').read()
n0 = len(s)
ok = []

def rep(old, new, tag):
    global s
    if s.count(old) != 1:
        print('❌ [%s] 锚点命中 %d 次（须为 1）' % (tag, s.count(old)))
        sys.exit(1)
    s = s.replace(old, new)
    ok.append(tag)

# ── 1. MASTERY 段头：标题 + 首段（改名 + 三档说明 + 新表） ──
rep(
"""  /* ============================================================
   * 满级专精（v28 · 需求 1）
   * ------------------------------------------------------------
   * 建筑上限由 10 提到 12 之后，"12 级"必须给出**机制层**的回报，
   * 否则玩家到 10 级就没有目标、11/12 级只是两行更贵的数字。
   *""",
"""  /* ============================================================
   * 建筑专精（v28 建 · v89.137 更名与三档）
   * ------------------------------------------------------------
   * v89.137（老板 5）：「建筑的专精改名为"建筑专精"，分别在 12，24，36 级时
   *   增加效果（因为 12 级不是满级了现在）」。
   * · 旧名"满级专精"：满 12 级给一条加成 —— 那是建筑上限还是 12 的年代。
   *   但上限早已随名城（+4/+8/+12）与主城爵位（+21）抬到 16~45，
   *   12 级不再是终点，13 级往上是一段"只有数字、没有机制"的空窗；
   * · 新口径 = **三档阶梯**：Lv12 / Lv24 / Lv36 各记一档，
   *   效果 = 本表 val × 档数（**第一档保持原值 —— 已上线数值不变**，
   *   24 级 ×2、36 级 ×3 —— "到一档，加一层"）；
   * · 门槛是数据（`DATA.MASTERY_TIERS`），档数判定走唯一出口
   *   `GAME.masteryTierOf(city, bid)`（domain.js）；档数消费走 `GAME.mastery(key, city)`
   *   （已返回"val × 档数"，消费点不必自己乘）。
   *
   * 为什么是 12/24/36：它们正是"基准满级 / 州城-都城带 / 主城满爵带"
   * 的三道坎（自建城 12 · 州城 20 · 都城 24 · 主城满爵 45），
   * 玩家每到一档都有机制层回报，中段不再空窗。
   * ============================================================ */
  DATA.MASTERY_TIERS = [12, 24, 36];

  /* ============================================================
   * 建筑专精 · 效果表（v28 初版 · 各条 val 即"第一档"值）
   * ------------------------------------------------------------""",
'MASTERY 段头')

# ── 2. honglusi 注释两处 ──
rep('       这个 id 被存档键、10 篇故事锚点（bld-honglusi-01..10）、满级专精、',
    '       这个 id 被存档键、10 篇故事锚点（bld-honglusi-01..10）、建筑专精、',
    'honglusi-1')
