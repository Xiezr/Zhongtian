import io

def patch(path, marker, block, tail_expect):
    d = io.open(path, encoding='utf-8', newline='').read()
    if marker in d:
        print('SKIP', path.split('\\')[-1])
        return
    nl = '\r\n' if '\r\n' in d[:4000] else '\n'
    t = d.rstrip('\r\n')
    if not t.endswith(tail_expect):
        raise SystemExit('!! tail 校验失败 %s : %s' % (path, tail_expect[:48]))
    t = t + nl + nl + block.replace('\n', nl) + nl
    io.open(path, 'w', encoding='utf-8', newline='').write(t)
    print('OK', path.split('\\')[-1])

